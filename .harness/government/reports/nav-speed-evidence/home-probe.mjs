import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const require = createRequire('/Users/jordanknight/substrate/chainglass/package.json');
const { chromium } = require('playwright');
const base = 'http://localhost:3000';
const path = process.argv[2] ?? '/';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
const code = JSON.parse(readFileSync('/Users/jordanknight/substrate/chainglass/.chainglass/bootstrap-code.json', 'utf8')).code;
await ctx.request.post(base + '/api/bootstrap/verify', { data: { code } });
const page = await ctx.newPage();
const t0 = Date.now();
const start = new Map(); const rows = [];
page.on('request', (r) => start.set(r, Date.now()));
page.on('requestfinished', (r) => { const u = new URL(r.url()); rows.push({ at: start.get(r) - t0, ms: Date.now() - start.get(r), type: r.resourceType(), k: `${r.method()} ${u.pathname}`, rsc: !!r.headers()['rsc'], prefetch: r.headers()['next-router-prefetch'] ?? r.headers()['next-router-segment-prefetch'] ?? null }); });
await page.goto(base + path, { waitUntil: 'load', timeout: 180_000 });
const tLoad = Date.now() - t0;
await page.waitForTimeout(6000);
const nav = await page.evaluate(() => { const n = performance.getEntriesByType('navigation')[0]; return { responseEnd: Math.round(n.responseEnd), dcl: Math.round(n.domContentLoadedEventEnd), fcp: Math.round(performance.getEntriesByName('first-contentful-paint')[0]?.startTime ?? -1) }; });
console.log('tLoad', tLoad, JSON.stringify(nav));
const non = rows.filter((r) => r.type !== 'script' && r.type !== 'image' && r.type !== 'stylesheet' && r.type !== 'font');
console.log('non-asset requests', non.length, 'prefetch', non.filter((r) => r.prefetch).length);
for (const r of non.sort((a, b) => a.at - b.at)) console.log(String(r.at).padStart(6), String(r.ms).padStart(6) + 'ms', r.prefetch ? 'PREFETCH' : (r.rsc ? 'RSC' : '-'), r.k);
await browser.close();
